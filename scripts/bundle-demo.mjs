// Bundles demo-repo/ into a TS module so the serverless functions never depend on file tracing.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../demo-repo/", import.meta.url));
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(root, p)] = readFileSync(p, "utf8");
  }
})(root);

const out = `// AUTO-GENERATED by scripts/bundle-demo.mjs from demo-repo/. Do not edit.\nexport const DEMO_REPO_NAME = "harbor-api";\nexport const DEMO_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(new URL("../lib/demo/bundle.generated.ts", import.meta.url), out);
console.log(`bundled ${Object.keys(files).length} demo files`);
